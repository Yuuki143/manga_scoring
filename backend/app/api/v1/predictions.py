"""Hit prediction endpoints for the MMIP API.

Routes
------
GET /trends/predictions – Ranked list of titles predicted to grow
                          significantly, using the three-strategy HitPredictor.
"""

from datetime import datetime
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy.orm import Session

from app.auth.audit import log_action
from app.auth.dependencies import get_current_user
from app.database import get_db
from app.models.publisher import Publisher
from app.schemas.prediction import PredictionEntry, PredictionResponse
from app.scoring.predictions import HitPredictor

router = APIRouter()


def _get_publisher(user, db: Session) -> Publisher:
    """Return the active publisher for the authenticated user.

    Raises:
        HTTPException 404: If the publisher is not found or inactive.
    """
    publisher: Publisher | None = (
        db.query(Publisher)
        .filter(Publisher.id == user.publisher_id, Publisher.is_active.is_(True))
        .first()
    )
    if publisher is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Publisher account not found or inactive",
        )
    return publisher


def _get_client_ip(request: Request) -> Optional[str]:
    """Extract the originating client IP address."""
    forwarded_for = request.headers.get("X-Forwarded-For")
    if forwarded_for:
        return forwarded_for.split(",")[0].strip()
    return request.client.host if request.client else None


@router.get(
    "/predictions",
    response_model=PredictionResponse,
    summary="Get hit predictions for trending manga titles",
    description=(
        "Returns up to 20 manga titles predicted to experience significant "
        "commercial growth, ranked by estimated uplift. Three detection "
        "strategies are used: **anime-linked growth** (titles with a recent "
        "anime showing measurable uplift), **anime candidates** (popular "
        "titles without an anime that fit high-lift genres), and "
        "**overseas expansion** (strong domestic titles with low international "
        "penetration). "
        "The requesting publisher's own titles are shown with real names; "
        "competitor titles are anonymised."
    ),
)
async def get_predictions(
    request: Request,
    current_user=Depends(get_current_user),
    db: Session = Depends(get_db),
) -> PredictionResponse:
    """Return hit predictions generated by the three-strategy HitPredictor.

    Each entry in the response includes a prediction type, estimated growth
    rate, confidence score, and a list of human-readable explanatory factors.
    Competitor titles are anonymised; the requesting publisher's own titles
    are shown with their real names.

    Args:
        request: FastAPI request object.
        current_user: Authenticated user from JWT dependency.
        db: Database session.

    Raises:
        HTTPException 404: Publisher not found or inactive.
    """
    publisher = _get_publisher(current_user, db)

    predictor = HitPredictor(db)
    raw_predictions = predictor.get_predictions(publisher_id=publisher.id)

    # Map raw dicts to PredictionEntry schema, assigning rank positions
    entries: list[PredictionEntry] = []
    for rank, pred in enumerate(raw_predictions, start=1):
        entries.append(
            PredictionEntry(
                rank=rank,
                title_name=pred.get("title_name"),
                anonymous_label=pred.get("anonymous_label"),
                is_own_title=pred.get("is_own_title", False),
                prediction_type=pred.get("prediction_type", ""),
                predicted_growth=pred.get("predicted_growth", 0.0),
                confidence=pred.get("confidence", 0.0),
                factors=pred.get("factors", []),
            )
        )

    tier_str = (
        publisher.tier.value if hasattr(publisher.tier, "value") else str(publisher.tier)
    )

    log_action(
        db=db,
        action="predictions_view",
        resource_type="prediction",
        user_id=current_user.id,
        publisher_id=publisher.id,
        ip_address=_get_client_ip(request),
        details={"tier": tier_str, "prediction_count": len(entries)},
    )

    return PredictionResponse(
        predictions=entries,
        generated_at=datetime.utcnow(),
    )
